#!/usr/bin/env python3
"""
studio-sync: mirror the repo's Luau sources into an open Roblox Studio place through the Studio
MCP server, without Rojo (Claude sessions cannot click the Rojo plugin's Connect button).

  make studio-sync          bundles src/ + tests/ into build/studio-sync/ (manifest + files)
                            and writes build/studio-sync/sync.luau
  make studio-sync-serve    serves that folder on http://127.0.0.1:8766 (run it in the background)

Then pass the content of build/studio-sync/sync.luau to the MCP tool `execute_luau` (Edit mode,
not while playing). It creates/updates every script to match the repo (same layout as
test.project.json) and deletes scripts that no longer exist in the repo, under the managed roots
only. Re-run `make studio-sync` after each edit; the server keeps serving the refreshed bundle.
"""
import json
import os
import shutil

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, "build", "studio-sync")
PORT = int(os.environ.get("STUDIO_SYNC_PORT", "8766"))

# Mirrors test.project.json (game sources + specs + TestRunner).
ROOTS = {
    "src/shared": (["ReplicatedStorage", "Shared"], "Folder"),
    "src/server": (["ServerScriptService", "Server"], "Script"),
    "src/client": (["StarterPlayer", "StarterPlayerScripts", "Client"], "LocalScript"),
    "tests": (["ServerScriptService", "Tests"], "Folder"),
}

STUDIO_SCRIPT = r"""-- Generated by tools/studio-sync.py: mirrors the repo's Luau files into the open place (Edit mode).
local HttpService = game:GetService("HttpService")
local BASE = "http://127.0.0.1:%PORT%/"

local manifest = HttpService:JSONDecode(HttpService:GetAsync(BASE .. "manifest.json"))
local changed, created, removed = {}, {}, {}
local expected = {}

local function resolve(path, finalClass)
	local node = game:GetService(path[1])
	for i = 2, #path do
		local name = path[i]
		local child = node:FindFirstChild(name)
		local wantClass = if i == #path then finalClass else nil
		if child and wantClass and child.ClassName ~= wantClass then
			-- A folder that became a script (or the reverse): keep its children.
			local replacement = Instance.new(wantClass)
			replacement.Name = name
			for _, grandChild in child:GetChildren() do
				grandChild.Parent = replacement
			end
			child:Destroy()
			replacement.Parent = node
			child = replacement
			table.insert(created, table.concat(path, "."))
		elseif child == nil then
			child = Instance.new(wantClass or "Folder")
			child.Name = name
			child.Parent = node
			if wantClass then
				table.insert(created, table.concat(path, "."))
			end
		end
		node = child
	end
	return node
end

for _, entry in manifest.entries do
	local source = HttpService:GetAsync(BASE .. entry.file)
	local instance = resolve(entry.path, entry.class)
	expected[instance] = true
	if instance.Source ~= source then
		instance.Source = source
		table.insert(changed, table.concat(entry.path, "."))
	end
end

-- Remove scripts that no longer exist in the repo (managed roots only).
for _, root in manifest.roots do
	local node = game:GetService(root.path[1])
	for i = 2, #root.path do
		node = node and node:FindFirstChild(root.path[i])
	end
	if node then
		expected[node] = true
		for _, descendant in node:GetDescendants() do
			if descendant:IsA("LuaSourceContainer") and not expected[descendant] then
				table.insert(removed, descendant:GetFullName())
				descendant:Destroy()
			end
		end
	end
end

return `synced {#manifest.entries} files | changed {#changed}: {table.concat(changed, ", ")} | created {#created}: {table.concat(created, ", ")} | removed {#removed}: {table.concat(removed, ", ")}`
"""


def main() -> None:
    files_dir = os.path.join(OUT, "files")
    if os.path.isdir(files_dir):
        shutil.rmtree(files_dir)
    entries = []
    for rel, (target, root_class) in ROOTS.items():
        base = os.path.join(REPO, rel)
        for dirpath, _, names in os.walk(base):
            for filename in sorted(names):
                if not filename.endswith(".luau"):
                    continue
                full = os.path.join(dirpath, filename)
                sub = os.path.relpath(full, base)
                parts = sub.split(os.sep)
                name = parts[-1][: -len(".luau")]
                if len(parts) == 1 and name in ("init.server", "init.client"):
                    path, cls = target, root_class
                elif name == "init":
                    # Rojo: a folder with init.luau is a ModuleScript holding its siblings.
                    path, cls = target + parts[:-1], "ModuleScript"
                else:
                    cls = "ModuleScript"
                    for suffix, script_class in ((".server", "Script"), (".client", "LocalScript")):
                        if name.endswith(suffix):
                            name, cls = name[: -len(suffix)], script_class
                    path = target + parts[:-1] + [name]
                key = f"{rel}/{sub}"
                dest = os.path.join(files_dir, key)
                os.makedirs(os.path.dirname(dest), exist_ok=True)
                shutil.copyfile(full, dest)
                entries.append({"file": "files/" + key, "path": path, "class": cls})
    manifest = {
        "roots": [{"path": target, "class": cls} for target, cls in ROOTS.values()],
        "entries": entries,
    }
    with open(os.path.join(OUT, "manifest.json"), "w") as handle:
        json.dump(manifest, handle)
    with open(os.path.join(OUT, "sync.luau"), "w") as handle:
        handle.write(STUDIO_SCRIPT.replace("%PORT%", str(PORT)))
    print(f"studio-sync: {len(entries)} files -> build/studio-sync (serve with: make studio-sync-serve)")


if __name__ == "__main__":
    main()
